import { readdir, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const imagesDir = join(root, 'public', 'images');
const outFile = join(root, 'src', 'data', 'imageManifest.js');

const IMAGE_EXT = /\.(jpe?g|png|gif|webp|avif|svg)$/i;
const FORMAT_PRIORITY = ['webp', 'jpg', 'jpeg', 'png', 'gif', 'avif', 'svg'];

const baseName = (f) => f.replace(/\.[^.]+$/, '').toLowerCase();

const dirs = await readdir(imagesDir, { withFileTypes: true });
const manifest = {};

for (const dir of dirs) {
  if (!dir.isDirectory()) continue;
  const folderFull = join(imagesDir, dir.name);
  const files = (await readdir(folderFull)).filter((f) => IMAGE_EXT.test(f)).sort();
  if (files.length === 0) continue;

  const byBase = new Map();
  for (const f of files) {
    const base = baseName(f);
    const ext = f.split('.').pop().toLowerCase();
    const existing = byBase.get(base);
    if (!existing) {
      byBase.set(base, f);
    } else {
      const existingExt = existing.split('.').pop().toLowerCase();
      if (FORMAT_PRIORITY.indexOf(ext) < FORMAT_PRIORITY.indexOf(existingExt)) {
        byBase.set(base, f);
      }
    }
  }

  const folderSegment = dir.name.split('/').map(encodeURIComponent).join('/');
  manifest[dir.name.toLowerCase()] = [...byBase.values()].map((f) => {
    const fileSegment = f.split('/').map(encodeURIComponent).join('/');
    return `/images/${folderSegment}/${fileSegment}`;
  });
}

const cityLines = Object.entries(manifest)
  .map(
    ([city, paths]) =>
      `  '${city}': [\n${paths.map((p) => `    '${p}'`).join(',\n')}\n  ]`
  )
  .join(',\n');

const content = `// AUTO-GENERATED by scripts/generate-image-manifest.mjs. Do not edit manually.
// Regenerate with: npm run generate:images
export const imageManifest = {
${cityLines}
};
`;

await writeFile(outFile, content, 'utf8');
console.log(`Wrote ${outFile} (${Object.keys(manifest).length} cities)`);
